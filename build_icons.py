"""Build the Pokémon icons used by pokemon-icat, optionally packed in a data archive.

For every row of bin/pokemon_data.csv (row N is national dex number N), the
normal and shiny sprites are downloaded from PokeAPI/sprites at a pinned
commit, cropped to their visible pixels, upscaled and saved as
<output>/{normal,shiny}/<name>.png. The same inputs always give the same files.

Usage:
    python3 build_icons.py                       # into $POKEMON_ICAT_DATA/pokemon-icons
    python3 build_icons.py -o icons -u 5         # custom directory and upscale factor
    python3 build_icons.py -o build/pokemon-icons --archive dist/pokemon-icat-data-1.0.0.tar.zst

The archive holds a single pokemon-icat-data/ directory with pokemon_data.csv,
pokemon-icons/ and a NOTICE: its content goes as is to /usr/share/pokemon-icat.

Requires Pillow; --archive also needs GNU tar and zstd.
"""

import argparse
import csv
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from io import BytesIO
from pathlib import Path

from PIL import Image

# PokeAPI/sprites commit the icons are built from (bump it to pick up new sprites)
SPRITES_REF = "961f4fcc85b159f9c5fff356356dee1bf9069898"
SPRITE_URL = "https://raw.githubusercontent.com/PokeAPI/sprites/{ref}/sprites/pokemon/{variant}{id}.png"
VARIANTS = {"normal": "", "shiny": "shiny/"}

DATA_CSV = Path(__file__).parent / "bin" / "pokemon_data.csv"


def download(url: str, attempts: int = 4) -> bytes:
    for attempt in range(attempts):
        try:
            with urllib.request.urlopen(url, timeout=30) as response:
                return response.read()
        except OSError:
            if attempt == attempts - 1:
                raise
            time.sleep(2**attempt)
    raise AssertionError("unreachable")


def build_icon(url: str, destination: Path, upscale: float) -> None:
    image = Image.open(BytesIO(download(url)), formats=["png"]).convert("RGBA")
    bbox = image.getbbox()
    if bbox is None:
        raise ValueError(f"{url} is fully transparent")
    image = image.crop(bbox)
    size = (round(image.width * upscale), round(image.height * upscale))
    image.resize(size, Image.BOX).save(destination, optimize=True)


def build_icons(output: Path, upscale: float, ref: str, jobs: int) -> None:
    with DATA_CSV.open(newline="", encoding="utf-8") as f:
        names = [row["name"] for row in csv.DictReader(f)]

    tasks = []
    for variant, prefix in VARIANTS.items():
        (output / variant).mkdir(parents=True, exist_ok=True)
        for dex_id, name in enumerate(names):
            url = SPRITE_URL.format(ref=ref, variant=prefix, id=dex_id)
            tasks.append((url, output / variant / f"{name}.png"))

    failures = []
    with ThreadPoolExecutor(max_workers=jobs) as pool:
        futures = {pool.submit(build_icon, url, dest, upscale): url for url, dest in tasks}
        for done, (future, url) in enumerate(futures.items(), start=1):
            try:
                future.result()
            except Exception as e:
                failures.append(f"{url}: {type(e).__name__}: {e}")
            print(f"\r{done}/{len(tasks)} icons", end="", file=sys.stderr)
    print(file=sys.stderr)

    # every CSV entry must have both icons, and nothing else may be there
    expected = {f"{name}.png" for name in names}
    for variant in VARIANTS:
        present = {p.name for p in (output / variant).iterdir()}
        failures += [f"missing {variant}/{n}" for n in sorted(expected - present)]
        failures += [f"unexpected {variant}/{n}" for n in sorted(present - expected)]

    if failures:
        sys.exit("icon build failed:\n  " + "\n  ".join(failures))
    print(f"{len(tasks)} icons written to {output}")


def write_notice(path: Path, upscale: float, ref: str) -> None:
    path.write_text(
        "Data for pokemon-icat (https://github.com/aflaag/pokemon-icat):\n"
        "pokemon_data.csv and the Pokémon icons in pokemon-icons/\n"
        "\n"
        f"Source: https://github.com/PokeAPI/sprites at commit {ref}\n"
        f"Processing: cropped to the visible pixels, upscaled x{upscale:g} (box filter)\n"
        "Localized names: https://github.com/PokeAPI/pokeapi (update_names.py)\n"
        "Generated by build_icons.py from the pokemon-icat repository.\n"
        "\n"
        "Pokémon and Pokémon character names are trademarks of Nintendo.\n"
        "The sprites are © Nintendo / Creatures Inc. / GAME FREAK inc.\n",
        encoding="utf-8",
    )


def make_archive(icons_dir: Path, archive: Path, upscale: float, ref: str) -> None:
    """Reproducible .tar.zst (sorted entries, fixed mtime and owner) of the CSV, icons and NOTICE."""
    archive.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        stage = Path(tmp) / "pokemon-icat-data"
        stage.mkdir()
        shutil.copy2(DATA_CSV, stage / DATA_CSV.name)
        shutil.copytree(icons_dir, stage / "pokemon-icons")
        write_notice(stage / "NOTICE", upscale, ref)
        pack(stage, archive)


def pack(directory: Path, archive: Path) -> None:
    tar = subprocess.Popen(
        [
            "tar",
            "--sort=name",
            "--mtime=@0",
            "--owner=0",
            "--group=0",
            "--numeric-owner",
            "--mode=go=rX,u+rw,a-s",
            "--format=gnu",
            "-C",
            str(directory.parent),
            "-cf",
            "-",
            directory.name,
        ],
        stdout=subprocess.PIPE,
    )
    with archive.open("wb") as out:
        subprocess.run(["zstd", "-19", "-q", "-c"], stdin=tar.stdout, stdout=out, check=True)
    if tar.wait() != 0:
        sys.exit("tar failed")

    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    (archive.parent / f"{archive.name}.sha256").write_text(f"{digest}  {archive.name}\n")
    print(f"{archive} ({archive.stat().st_size / 1e6:.1f} MB)\nsha256 {digest}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    data_dir = os.environ.get("POKEMON_ICAT_DATA")
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path(data_dir) / "pokemon-icons" if data_dir else None,
        required=data_dir is None,
        help="icons directory (default: $POKEMON_ICAT_DATA/pokemon-icons)",
    )
    parser.add_argument("-u", "--upscale", type=float, default=3, metavar="FACTOR", help="upscale factor (default: 3)")
    parser.add_argument("--sprites-ref", default=SPRITES_REF, metavar="REF", help="PokeAPI/sprites commit or branch")
    parser.add_argument("-j", "--jobs", type=int, default=16, help="parallel downloads (default: 16)")
    parser.add_argument("--archive", type=Path, metavar="FILE", help="also pack the CSV and icons into this .tar.zst")
    args = parser.parse_args()

    build_icons(args.output, args.upscale, args.sprites_ref, args.jobs)
    if args.archive:
        make_archive(args.output, args.archive, args.upscale, args.sprites_ref)


if __name__ == "__main__":
    main()
